"""Build the baseline-comparison LaTeX table for the paper.

Consumes the per-slice CSVs written by ``quantiles_selective.py``, ``scpi_selective.py``,
``random_selective.py`` and the M2 results table, aggregates them over assets, and
writes a granularity x method table of Precision / Coverage (and optionally Return)
split by direction.

Usage:
    python -m Utils.selective_classification.baselines.transfer_baselines_table \\
        --m2-results  Output/.../m2_results.csv \\
        --pi          Output/.../pi_metrics.csv \\
        --spci        Output/.../spci_metrics.csv \\
        --random      Output/.../random_metrics.csv \\
        --out         /home/pablo/M2_DS/Papers/ESWA26/baselines.tex
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from Utils.selective_classification.baselines._common import GRANULARITIES

# Row order in the emitted table: M2 variants first, then the gates, then the control.
METHOD_ORDER = ("M2 RF", "M2 TabPFN", "M2 TabICL", "M2 AutoGluon", "M2 CNNT",
                "M1+PI", "M1+SPCI", "Random", "M1 (all)")

DEFAULT_OUT = Path("/home/pablo/M2_DS/Papers/ESWA26/baselines.tex")


def _load(path: Path | None) -> pd.DataFrame:
    """Read a per-slice CSV, dropping skipped rows."""
    if path is None or not Path(path).exists():
        return pd.DataFrame()
    df = pd.read_csv(path)
    if "skipped_reason" in df.columns:
        df = df[df["skipped_reason"].fillna("") == ""]
    return df


def _canonical_method(df: pd.DataFrame) -> pd.DataFrame:
    """Normalize the method label (e.g. 'M1+SPCI(directional)' -> 'M1+SPCI')."""
    if "method" not in df.columns:
        return df
    out = df.copy()
    out["method"] = out["method"].astype(str).str.replace(r"\(.*\)", "", regex=True).str.strip()
    return out


def collect(m2: Path | None, pi: Path | None, spci: Path | None,
            random_: Path | None) -> pd.DataFrame:
    """Stack every source into one long frame: method, granularity, side, metrics."""
    frames = []

    df_m2 = _load(m2)
    if not df_m2.empty:
        d = df_m2.copy()
        # An M2 table may name its model column 'm2_model' or 'model'.
        label_col = next((c for c in ("m2_model", "model", "method") if c in d.columns), None)
        d["method"] = ("M2 " + d[label_col].astype(str)) if label_col else "M2"
        d["method"] = d["method"].str.replace("M2 M2 ", "M2 ", regex=False)
        frames.append(d)

    for path in (pi, spci):
        d = _canonical_method(_load(path))
        if not d.empty:
            frames.append(d)

    d_rand = _load(random_)
    if not d_rand.empty:
        # The control's headline number is the random-gate mean precision.
        d = d_rand.copy()
        d["method"] = "Random"
        if "random_mean" in d.columns:
            d["precision"] = d["random_mean"]
        if "target_coverage" in d.columns:
            d["coverage"] = d["target_coverage"]
        frames.append(d)

    if not frames:
        raise SystemExit("No input tables found — nothing to build.")

    keep = ["method", "granularity", "side", "precision", "coverage",
            "m1_precision", "p_value", "total_return"]
    stacked = pd.concat(frames, ignore_index=True, sort=False)
    return stacked[[c for c in keep if c in stacked.columns]]


def aggregate(df: pd.DataFrame) -> pd.DataFrame:
    """Mean over assets → one row per (method, granularity, side)."""
    metrics = [c for c in ("precision", "coverage", "total_return", "p_value") if c in df.columns]
    return df.groupby(["method", "granularity", "side"], as_index=False)[metrics].mean(numeric_only=True)


def _fmt(v: float, pct: bool = True) -> str:
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "--"
    return f"{100.0 * v:.1f}" if pct else f"{v:.3f}"


def build_latex(agg: pd.DataFrame, granularities, caption: str, label: str) -> str:
    """Emit a booktabs table: rows = methods, columns = granularity x {UP, DOWN}."""
    grans = [g for g in granularities if g in set(agg["granularity"])]
    methods = [m for m in METHOD_ORDER if m in set(agg["method"])]
    methods += sorted(set(agg["method"]) - set(methods))

    col_spec = "l" + "".join("cc" for _ in grans)
    lines = [
        "% Auto-generated by transfer_baselines_table.py — do not edit by hand.",
        "\\begin{table*}[t]",
        "  \\centering",
        "  \\small",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        f"  \\begin{{tabular}}{{{col_spec}}}",
        "    \\toprule",
        "    Method & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{g}}}" for g in grans) + " \\\\",
        "    " + " ".join(f"\\cmidrule(lr){{{2*i+2}-{2*i+3}}}" for i in range(len(grans))),
        "    & " + " & ".join("UP & DOWN" for _ in grans) + " \\\\",
        "    \\midrule",
    ]

    for method in methods:
        cells = []
        for g in grans:
            for side in ("up", "down"):
                row = agg[(agg["method"] == method) & (agg["granularity"] == g)
                          & (agg["side"].astype(str).str.lower() == side)]
                cells.append(_fmt(float(row["precision"].iloc[0]) if not row.empty else np.nan))
        safe = method.replace("&", "\\&").replace("_", "\\_")
        lines.append(f"    {safe} & " + " & ".join(cells) + " \\\\")

    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


def main() -> None:
    p = argparse.ArgumentParser(description="Build baselines.tex from per-slice CSVs.")
    p.add_argument("--m2-results", type=Path, default=None)
    p.add_argument("--pi", type=Path, default=None)
    p.add_argument("--spci", type=Path, default=None)
    p.add_argument("--random", dest="random_", type=Path, default=None)
    p.add_argument("--granularities", nargs="+", default=list(GRANULARITIES))
    p.add_argument("--caption", default="Selective precision (\\%) of the proposed $M2$ models "
                                        "against uncertainty-based and random-coverage baselines, "
                                        "per granularity and direction. Higher is better.")
    p.add_argument("--label", default="tab:baselines")
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    p.add_argument("--dump-csv", type=Path, default=None,
                   help="Optional: also write the aggregated long table as CSV.")
    args = p.parse_args()

    agg = aggregate(collect(args.m2_results, args.pi, args.spci, args.random_))
    tex = build_latex(agg, args.granularities, args.caption, args.label)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(tex, encoding="utf-8")
    if args.dump_csv:
        args.dump_csv.parent.mkdir(parents=True, exist_ok=True)
        agg.to_csv(args.dump_csv, index=False)

    print(f"Wrote {args.out}  ({agg['method'].nunique()} methods x "
          f"{agg['granularity'].nunique()} granularities)")


if __name__ == "__main__":
    main()
